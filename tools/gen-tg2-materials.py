#!/usr/bin/env python3
"""gen-tg2-materials.py -- palette D (owner locked "Gouache Frontier",
2026-09-25; "add the materials now", 2026-09-26) into the ENGINE, from one
source: tools/palette_defs.py.

Every non-fluid TerrainGen material g becomes engine id TG2_BASE + g (128 + g),
so the mapping needs no table and reads back trivially. Fluids keep their
existing engine ids (their behaviour lives there). Colours: D's hex / 255 --
the same encoding MaterialPalette authors in -- with the palette's own
clipping lesson applied (snow was lowered 0.86 -> 0.72 because bright albedo
blows out under the sky term): any colour whose brightest channel exceeds CAP
is scaled down to it, hue kept.

Prints the generated blocks; --write patches them into:
  Assets/ContentModules/MaterialRules.cs   MaterialPalette's TG2 table
  Assets/CoreEngine/Rendering/Raymarch.compute   the TG2 albedo table
between the markers  // >>> TG2 PALETTE (generated)  and  // <<< TG2 PALETTE
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from palette_defs import PALETTES, NAMES, B10_CANDIDATES  # noqa: E402

TG2_BASE = 128
CAP = 0.76        # MaterialPalette (look 0, linear-authored mid values)
CAP_LOOK = 0.95   # the look-1 palette (display space; its snow is 0.93)
FLUIDS = {1, 2, 3, 4, 5, 6, 7}
D = dict(PALETTES["D"][2])
# --b10 <key>: write a B10 savanna/badlands colour candidate instead of the
# shipped one (palette_defs.B10_SHIPPED), to render it in the engine.
if "--b10" in sys.argv:
    D.update(B10_CANDIDATES[sys.argv[sys.argv.index("--b10") + 1]][1])


def capped(rgb, cap):
    m = max(rgb)
    k = cap / m if m > cap else 1.0
    return tuple(round(c * k, 3) for c in rgb)


def table(cap):
    """index i (0..95) -> (r, g, b, name) for engine id TG2_BASE + i, or None."""
    out = [None] * 96
    for g, rgb in sorted(D.items()):
        if g in FLUIDS or g >= 96:
            continue
        r, gg, b = capped(rgb, cap)
        out[g] = (r, gg, b, NAMES[g])
    return out


def cs_block(t, cap, var, target, tag):
    lines = [f"        // >>> TG2 PALETTE{tag} (generated by tools/gen-tg2-materials.py from palette D -- do not hand-edit)",
             "        // Engine id = Materials.TG2_BASE + TerrainGen GenMat code. Colours: D's hex / 255, capped at",
             f"        // {cap} per channel (hue kept) -- the snow clipping lesson.",
             f"        float[] {var} = {{"]
    for i, e in enumerate(t):
        if e is None:
            lines.append(f"            -1f, -1f, -1f,   // {TG2_BASE + i}")
        else:
            lines.append(f"            {e[0]:.3f}f, {e[1]:.3f}f, {e[2]:.3f}f,   // {TG2_BASE + i} {e[3]}")
    lines += ["        };",
              f"        for (int i = 0; i < {var}.Length / 3; i++)",
              f"            if ({var}[i * 3] >= 0f) {target}[Materials.TG2_BASE + i] = new Rgb({var}[i * 3], {var}[i * 3 + 1], {var}[i * 3 + 2]);",
              f"        // <<< TG2 PALETTE{tag}"]
    return "\n".join(lines)


def hlsl_table(t, name):
    lines = [f"static const float3 {name}[96] = {{"]
    for i, e in enumerate(t):
        if e is None:
            lines.append(f"    float3(0.900, 0.100, 0.800),   // {TG2_BASE + i} (none)")
        else:
            lines.append(f"    float3({e[0]:.3f}, {e[1]:.3f}, {e[2]:.3f}),   // {TG2_BASE + i} {e[3]}")
    lines[-1] = lines[-1].replace("),   //", ")    //")
    lines += ["};"]
    return lines


def hlsl_block(t, tl):
    lines = ["// >>> TG2 PALETTE (generated by tools/gen-tg2-materials.py from palette D -- do not hand-edit)",
             "// Engine ids 128..223 = TG2_BASE + TerrainGen GenMat code. Tables, not more ifs: 96 entries",
             "// each, and a lookup costs the same for all of them. Unauthored -> magenta. kTg2Palette mirrors",
             f"// MaterialPalette.Of (cap {CAP}); kTg2PaletteLook mirrors MaterialPalette.OfLook (cap {CAP_LOOK})."]
    lines += hlsl_table(t, "kTg2Palette") + hlsl_table(tl, "kTg2PaletteLook") + ["// <<< TG2 PALETTE"]
    return "\n".join(lines)


def patch(path, block, tag=""):
    src = open(path).read()
    rx = re.compile(r"[ \t]*// >>> TG2 PALETTE" + re.escape(tag) + r" .*?// <<< TG2 PALETTE" + re.escape(tag) + r"\n", re.S)
    if not rx.search(src):
        raise SystemExit(f"markers not found in {path}")
    open(path, "w").write(rx.sub(lambda _: block + "\n", src, count=1))


if __name__ == "__main__":
    t, tl = table(CAP), table(CAP_LOOK)
    cs0 = cs_block(t, CAP, "tg2", "_table", "")
    cs1 = cs_block(tl, CAP_LOOK, "tg2Look", "t", " LOOK")
    hl = hlsl_block(t, tl)
    if "--write" in sys.argv:
        patch("Assets/ContentModules/MaterialRules.cs", cs0, "")
        patch("Assets/ContentModules/MaterialRules.cs", cs1, " LOOK")
        patch("Assets/CoreEngine/Rendering/Raymarch.compute", hl, "")
        print(f"patched: {sum(e is not None for e in t)} TG2 materials")
    else:
        print(cs0); print(); print(cs1); print(); print(hl)
