#!/bin/bash
# tools/cleanup-disk.sh -- free disk space by deleting regenerable / stale files (task 129a, owner 2026-10-23).
#
#   tools/cleanup-disk.sh            DRY RUN: writes Logs/cleanup/PLAN.txt, deletes nothing
#   APPLY=1 tools/cleanup-disk.sh    deletes category A, manifest in Logs/cleanup/DELETED.txt
#
# Category A (deleted): Builds scratch folders, Logs older than 7 days, root test/build logs, unreferenced
#   untracked Screenshots intermediates, old standalone-rig run folders in Application Support, dev-tool caches.
# Category B (report only): sibling projects, big files, snapshots, Screenshots per task, anything uncertain.
# NEVER deleted: git-tracked files, .git, Assets, ProjectSettings, Packages, Library, UserSettings, tools,
#   *.md, saves/worlds (dirs with world.meta), PlaySettings.json / PlayerConfig.json, anything under tools/overnight,
#   anything modified in the last 24 h (builds) / 7 days (logs, captures), any name a doc/HANDOFF/TASKS mentions.
# Uses the shared Unity lock when APPLY=1 (tools/unity-lock.sh). Never run two Unity things at once.
set -u
cd "$(dirname "$0")/.." || exit 1
ROOT=$PWD
APPLY=${APPLY:-0}
OUT=Logs/cleanup
mkdir -p "$OUT"
PLAN=$OUT/PLAN.txt
DEL=$OUT/DELETED.txt
CAND=$OUT/candidates.tsv      # kb <TAB> path <TAB> reason <TAB> needref(0/1)
KEEP=$OUT/kept_referenced.txt
CORPUS=$OUT/corpus.txt
APPSUP="$HOME/Library/Application Support/DefaultCompany/Voxel Terraria 1 Byte BrickMap"
: > "$CAND"; : > "$KEEP"

if [ "$APPLY" = 1 ]; then
  # shellcheck disable=SC1091
  source tools/unity-lock.sh
  unity_lock_acquire
fi

emit() { # kb path reason needref
  printf '%s\t%s\t%s\t%s\n' "$1" "$2" "$3" "$4" >> "$CAND"
}
kb_of() { du -sk "$1" 2>/dev/null | awk '{print $1}'; }
recent() { # recent PATH DAYS : true if anything inside changed within DAYS days
  [ -n "$(find "$1" -mtime -"$2" -print -quit 2>/dev/null)" ]
}

# ---- reference corpus: every doc that may cite a file by name ---------------------------------
{
  find . -maxdepth 1 -name '*.md' -o -maxdepth 1 -name '*.txt' | while read -r f; do cat "$f"; done
  find tools -type f \( -name '*.md' -o -name '*.txt' \) -print0 2>/dev/null | xargs -0 cat 2>/dev/null
  find Screenshots -type f -name '*.md' -print0 2>/dev/null | xargs -0 cat 2>/dev/null
} > "$CORPUS" 2>/dev/null

git ls-files > "$OUT/tracked.txt"

# ---- A1: Builds scratch (regenerated by every build; only crash symbolication is lost) ---------
for d in Builds/*_BackUpThisFolder_ButDontShipItWithYourGame Builds/*_BurstDebugInformation_DoNotShip \
         ./*_BurstDebugInformation_DoNotShip; do
  [ -d "$d" ] || continue
  recent "$d" 1 && { echo "keep (modified < 24 h): $d" >> "$KEEP"; continue; }
  emit "$(kb_of "$d")" "$d" "A1 build scratch, regenerated by the next build" 0
done
# Old copies of one build name: Builds/<Name>.app is a single folder per name, so only the newest exists; nothing to do.

# ---- A2: Logs older than 7 days -----------------------------------------------------------------
find Logs -type f -mtime +7 -not -path 'Logs/cleanup/*' -not -path 'Logs/overnight/runner.log' -print0 |
  while IFS= read -r -d '' f; do
    emit "$(( $(stat -f %z "$f") / 1024 ))" "$f" "A2 log older than 7 days" 1
  done

# ---- A3: root clutter regenerated by test runs/builds ---------------------------------------------
for f in TestResults*.xml unity_test*.log unity_filter*.log build.log fluid_tiled_build.log; do
  [ -f "$f" ] || continue
  [ "$f" = TestResults_all.xml ] && continue
  emit "$(( $(stat -f %z "$f") / 1024 ))" "$f" "A3 root test/build output" 0
done
# Il2CppOutputProject is partly git-tracked here (2 files), so it is left alone.

# ---- A4: Screenshots intermediates (untracked, unreferenced) --------------------------------------
{
  find Screenshots -type d \( -name 'try*' -o -name 'retry*' \) 2>/dev/null
  find Screenshots -type f \( -name '*.out' -o -name '*_spikes.csv' -o -name 'log_*.txt' \) 2>/dev/null
} | while IFS= read -r p; do
  case "$p" in */try*/*|*/retry*/*) continue;; esac     # inside an already-listed dir
  emit "$(kb_of "$p")" "$p" "A4 screenshot intermediate" 1
done

# ---- A5: standalone-rig capture folders in Application Support (not saves/settings) ----------------
if [ -d "$APPSUP" ]; then
  for F in "$APPSUP"/*/; do
    F=${F%/}; n=$(basename "$F")
    case "$n" in *World*|Unity|Presets) continue;; esac
    [ -n "$(find "$F" -maxdepth 2 -name 'world.meta' -print -quit)" ] && continue
    newest=$(ls -t "$F" 2>/dev/null | head -1); [ -n "$newest" ] || continue
    nt=$(stat -f %m "$F/$newest")
    ls -t "$F" | while IFS= read -r c; do
      p="$F/$c"
      case "$c" in *.json|*World*|*Save*|*save*) continue;; esac
      [ -n "$(find "$p" -maxdepth 2 -name 'world.meta' -print -quit 2>/dev/null)" ] && continue
      m=$(stat -f %m "$p")
      [ $((nt - m)) -lt 86400 ] && continue                       # same "run" as the newest
      [ -n "$(find "$p" -maxdepth 0 -mtime -7 -print)" ] && continue   # modified < 7 days
      emit "$(kb_of "$p")" "$p" "A5 old rig capture ($n)" 1
    done
  done
fi

# ---- A6: dev-tool caches that rebuild themselves ------------------------------------------------------
for p in "$HOME/Library/Unity/cache" "$HOME"/Library/Caches/com.unity3d.* "$HOME/Library/Caches/pip" \
         "$HOME/.npm/_cacache" "$HOME/Library/Caches/ms-playwright" "$HOME/Library/Caches/com.microsoft.VSCode.ShipIt" \
         "$HOME/Library/Developer/Xcode/DerivedData" "$HOME/Library/Developer/Xcode/iOS DeviceSupport" \
         "$HOME/Library/Application Support/UnityHub/Cache" "$HOME/Library/Caches/Homebrew" "$HOME"/.Trash/*; do
  [ -e "$p" ] || continue
  emit "$(kb_of "$p")" "$p" "A6 regenerable cache / Trash" 0
done
if ps -axco comm | grep -qix firefox; then
  echo "skip Firefox/Mozilla caches: Firefox is running" >> "$KEEP"
else
  for p in "$HOME/Library/Caches/Firefox" "$HOME/Library/Caches/Mozilla"; do
    [ -e "$p" ] && emit "$(kb_of "$p")" "$p" "A6 Firefox cache (not running)" 0
  done
fi

# ---- filter: tracked / protected / referenced ----------------------------------------------------------
# referenced set = every candidate basename that occurs in the corpus
awk -F'\t' '$4==1{n=split($2,a,"/"); print a[n]}' "$CAND" | sort -u > "$OUT/names.txt"
grep -oFh -f "$OUT/names.txt" "$CORPUS" 2>/dev/null | sort -u > "$OUT/refnames.txt"
awk -F'\t' -v root="$ROOT" '
  FILENAME ~ /tracked.txt$/ {t[$0]=1; next}
  FILENAME ~ /refnames.txt$/ {r[$0]=1; next}
  { p=$2; n=split(p,a,"/"); b=a[n]; keep="";
    if ($4==1 && (b in r)) keep="referenced by a doc";
    if (p ~ /^(\.git|Assets|ProjectSettings|Packages|Library|UserSettings|tools)(\/|$)/ || p ~ /\.md$/) keep="protected";
    if (p ~ /(PlaySettings|PlayerConfig)\.json$/) keep="settings";
    if (p !~ /^\//) { sub(/^\.\//,"",p); pre=p; while (1) { if (pre in t) {keep="git-tracked"; break}; i=match(pre,/\/[^\/]*$/); if(!i) break; pre=substr(pre,1,i-1) }  }
    if (keep!="") print "keep (" keep "): " p > "/dev/stderr"; else print $0 }
' "$OUT/tracked.txt" "$OUT/refnames.txt" "$CAND" > "$OUT/A_all.tsv" 2>> "$KEEP"
# directories that CONTAIN a tracked file (awk above only checks the path and its parents)
: > "$OUT/A.tsv"
while IFS=$'\t' read -r kb p why nr; do
  if [ -d "$p" ] && [ "${p#/}" = "$p" ] && [ -n "$(git ls-files -- "$p" | head -1)" ]; then echo "keep (contains tracked files): $p" >> "$KEEP"; continue; fi
  printf '%s\t%s\t%s\n' "$kb" "$p" "$why" >> "$OUT/A.tsv"
done < "$OUT/A_all.tsv"

# ---- PLAN ----------------------------------------------------------------------------------------------------
{
  echo "# cleanup plan $(date '+%F %T')  APPLY=$APPLY"
  df -h / | tail -1
  echo; echo "## Category A: will be deleted (kb, path, why). Totals per rule:"
  awk -F'\t' '{split($3,a," "); s[a[1]]+=$1; c[a[1]]++} END{for(k in s) printf "%s\t%d items\t%.2f GiB\n", k, c[k], s[k]/1048576}' "$OUT/A.tsv" | sort
  echo; echo "## top 25 items"; sort -rn "$OUT/A.tsv" | head -25 | awk -F'\t' '{printf "%8.0f MB  %s  [%s]\n",$1/1024,$2,$3}'
  echo; echo "## all items"; sort -rn "$OUT/A.tsv" | awk -F'\t' '{printf "%s\t%s\t%s\n",$1,$2,$3}'
  echo; echo "## Kept (referenced / protected / tracked / recent)"; cat "$KEEP"
} > "$PLAN"

# ---- Category B (report only) -----------------------------------------------------------------------------------
{
  echo; echo "## Category B: report only, nothing here is touched"
  echo "### sizes of known candidates (MB)"
  for p in "$ROOT/../VoxelTerraria_compare" "$ROOT/../Wortis-Dev" "$ROOT/../WortisBuild" "$ROOT/../VT_gemini2" \
           "$HOME/.ollama/models" "$HOME/Downloads" "$HOME/Unity Projects" "$HOME/Library/Caches" \
           "$HOME/Library/Developer" "$HOME/Library/Application Support" "$HOME/Desktop/Auto_Jobs_Applier_AI_Agent" \
           "$HOME/Desktop/ai-job-agent" "$HOME/Library/Application Support/Steam" /Applications/Unity* /Applications/6000* \
           "$ROOT/Library" "$ROOT/Screenshots" "$ROOT/Builds" "$ROOT/Logs"; do
    [ -e "$p" ] && printf '%8d MB  %s\n' "$(( $(kb_of "$p") / 1024 ))" "$p"
  done | sort -rn
  echo "### Screenshots per task folder (MB, top 30)"
  du -sk Screenshots/* 2>/dev/null | sort -rn | head -30 | awk '{printf "%8.0f MB  %s\n",$1/1024,$2}'
  echo "### 30 biggest files over 500 MB under ~ (project excluded)"
  find "$HOME" -xdev -path "$ROOT" -prune -o -type f -size +500M -print0 2>/dev/null | xargs -0 ls -lS 2>/dev/null |
    head -30 | awk '{printf "%8.0f MB  ", $5/1048576; $1=$2=$3=$4=$5=$6=$7=$8=""; print $0}'
  echo "### Time Machine local snapshots (not deleted)"; tmutil listlocalsnapshots / 2>&1 | head
  echo "### diskutil apfs (container/volumes)"; diskutil apfs list 2>&1 | grep -E 'Size|Capacity|Name:' | head -30
} >> "$PLAN" 2>&1

echo "plan: $PLAN  (A total: $(awk -F'\t' '{s+=$1} END{printf "%.2f GiB", s/1048576}' "$OUT/A.tsv"))"
[ "$APPLY" = 1 ] || { echo "dry run; APPLY=1 to delete"; exit 0; }

# ---- APPLY -------------------------------------------------------------------------------------------------------
before=$(df -k / | awk 'NR==2{print $4}')
: > "$DEL"
while IFS=$'\t' read -r kb p why; do
  case "$p" in *..*) echo "refuse: $p" >> "$DEL"; continue;; esac
  [ -e "$p" ] || continue
  printf '%s\t%s\t%s\n' "$kb" "$p" "$why" >> "$DEL"
  rm -rf -- "$p"
done < "$OUT/A.tsv"
if command -v brew >/dev/null 2>&1; then brew cleanup -s >> "$OUT/brew.log" 2>&1; echo "brew cleanup -s" >> "$DEL"; fi
after=$(df -k / | awk 'NR==2{print $4}')
{ echo; echo "## RESULT free before $((before/1048576)) GiB -> after $((after/1048576)) GiB"; df -h / | tail -1; } | tee -a "$PLAN" "$DEL"
