            LayerRange(out int lo, out int hi);
            for (int cy = lo; cy <= hi && missing.Count < max; cy++)
            for (int dz = -r; dz <= r && missing.Count < max; dz++)
            for (int dx = -r; dx <= r && missing.Count < max; dx++)
